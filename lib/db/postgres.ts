const globalForDb = globalThis as unknown as { clubmatesPool?: pg.Pool };

function connectionStringForServer(connectionString: string) {
  const withoutSslMode = connectionString.replace(/([?&])sslmode=[^&]*&?/gi, "$1").replace(/[?&]$/, "");
  let url: URL;
  try {
    url = new URL(withoutSslMode);
  } catch {
    return withoutSslMode;
  }

  const direct = url.hostname.match(/^db\.([a-z0-9]+)\.supabase\.co$/i);
  if (direct) {
    url.username = `postgres.${direct[1]}`;
    url.hostname = SUPABASE_POOLER_HOST;
    url.port = "6543";
  }

  return url.toString();
}

export function getPool() {
  const connectionString = process.env.DATABASE_URL?.trim();
  if (!connectionString) return null;
  if (globalForDb.clubmatesPool) return globalForDb.clubmatesPool;

  globalForDb.clubmatesPool = new pg.Pool({
    connectionString: connectionStringForServer(connectionString),
    max: 1,
    idleTimeoutMillis: 5_000,
    connectionTimeoutMillis: 10_000,
    allowExitOnIdle: true,
    ssl: { ca: SUPABASE_ROOT_CA, rejectUnauthorized: true },
  });

  return globalForDb.clubmatesPool;
}
